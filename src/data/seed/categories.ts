export type CategorieGroupe = { id: string; nom: string }

export type CategorieJoueur = {
  id: string
  nom: string
  /** Post code — see POSTE_LABEL. */
  poste: string
  /** The groupe of the catégorie the joueur trains with. */
  groupeId: string
  photo?: string
  /** "AAAA-MM-JJ". */
  naissance?: string
  /** Séances attended / held — the taux de présence is derived, never stored. */
  presences: number
  seances: number
}

export type CategorieMatch = {
  id: string
  /** ISO date-time. */
  date: string
  adversaire: string
  domicile: boolean
  type: "Championnat" | "Amical"
  /** A match still to be played has no score. */
  termine: boolean
  butsPour: number | null
  butsContre: number | null
  lieu: string | null
}

